"""
BOOTSTRAP DA REDE COLABORATIVA DE MICROAPOIOS

Responsável por iniciar oficialmente toda a Rede.
"""

import kernel


def bootstrap():

    print("========================================")
    print("BOOTSTRAP DA REDE")
    print("Iniciando sequência oficial...")
    print("========================================")

    kernel.iniciar()

    print("========================================")
    print("Bootstrap concluído.")
    print("========================================")


if __name__ == "__main__":
    bootstrap()
